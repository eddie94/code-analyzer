// Regenerate src/types/graph.ts from the pydantic models (the single source of truth).
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { compile } from "json-schema-to-typescript";

const schema = JSON.parse(
  execFileSync("uv", ["run", "--project", "..", "python", "-m", "codemap.model"], { encoding: "utf8" }),
);
writeFileSync("src/types/graph.schema.json", JSON.stringify(schema, null, 2) + "\n");

// json-schema-to-typescript predates `prefixItems`, and per-field titles turn into
// one alias type per field; normalize both before compiling.
function normalize(node, keepTitle) {
  if (Array.isArray(node)) return node.forEach(n => normalize(n, false));
  if (!node || typeof node !== "object") return;
  if (!keepTitle) delete node.title;
  if (node.prefixItems) {
    node.items = node.prefixItems;
    delete node.prefixItems;
  }
  for (const [key, value] of Object.entries(node)) {
    if (key === "$defs") Object.values(value).forEach(def => normalize(def, true));
    else normalize(value, false);
  }
}
const compiled = structuredClone(schema);
normalize(compiled, true);

const ts = await compile(compiled, "Graph", {
  additionalProperties: false,
  bannerComment: "/* Generated by `npm run gen:types` from codemap.model. Do not edit. */",
});
writeFileSync("src/types/graph.ts", ts);
console.log("Wrote src/types/graph.ts");
